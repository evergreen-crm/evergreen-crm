// (same questions, same instructions). They use the same engine as every other record (lib/entries.js),
// so saving, corrections with history and printing work the same way.
// Extra keys: area (Forms menu group), program (MCFD / CLBC / BOTH), source (manual + appendix),
// intro (when to complete it, who co-signs), signs (who reviews it, shown on the form).
// Saving some forms starts the next step automatically (supabase 008: form_* events → follow-up tasks).

const yn = (name, label, required = true) => ({ name, label, type: 'yesno', required });
const ta = (name, label, required = false) => ({ name, label, type: 'textarea', required });
const tx = (name, label, required = false) => ({ name, label, type: 'text', required });
const tm = (name, label, required = false) => ({ name, label, type: 'time', required });
const dt = (name, label, required = false) => ({ name, label, type: 'date', required });
const nu = (name, label, required = false, step) => ({ name, label, type: 'number', required, step });
const sel = (name, label, options, required = true) => ({ name, label, type: 'select', options, required });
const join = (...xs) => xs.filter(Boolean).join(' · ');
const todo = (pairs) => { const m = pairs.filter(([ok]) => !ok).map(([, t]) => t); return m.length ? `To do: ${m.join(', ')}` : null; };

