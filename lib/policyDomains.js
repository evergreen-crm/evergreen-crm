export function domainOf(code) {
  const key = BY_CODE[code] ?? OLD[code] ?? null;
  return DOMAINS.find((d) => d.key === key) ?? null;
}
export const domainLabel = (d) => (d ? `${d.key === 'D00' ? '00' : d.key} · ${d.name}` : 'Domain not set');
